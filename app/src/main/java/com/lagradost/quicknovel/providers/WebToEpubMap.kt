    fun getParserForUrl(url: String): String? {
        val trimmed = url.trim()
        val cleanUrl = if (!trimmed.startsWith("http://", ignoreCase = true) && !trimmed.startsWith("https://", ignoreCase = true)) {
            "https://$trimmed"
        } else {
            trimmed
        }
        val host = try {
            java.net.URL(cleanUrl).host.lowercase().removePrefix("www.")
        } catch (e: Exception) {
            return null
        }

        // Try exact match first
        exactMappings[host]?.let { return it }

        // Try exact match on subdomains/suffixes
        for ((domain, parser) in exactMappings) {
            if (host == domain || host.endsWith("." + domain)) {
                return parser
            }
        }

        // Try contains rules
        for ((pattern, parser) in containsMappings) {
            if (host.contains(pattern)) {
                return parser
            }
        }

        return null
    }
