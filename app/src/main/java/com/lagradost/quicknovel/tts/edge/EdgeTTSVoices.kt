data class EdgeVoice(
    val id: String,
    val name: String,
    val lang: String
) {
    fun toEngineVoice(): EngineVoice {
        val locale = try {
            Locale.forLanguageTag(lang)
        } catch (e: Exception) {
            Locale.getDefault()
        }
        return EngineVoice(
            name = "$name (Edge Neural)",
            locale = locale,
            isNetworkRequired = true
        )
    }
}

